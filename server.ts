import express from 'express';
import cookieParser from 'cookie-parser';
import path from 'node:path';
import apiRouter from './src/server/routes.ts';

const app = express();
const PORT = Number(process.env.PORT) || 3000;

app.use(express.json({ limit: '50mb' }));
app.use(express.urlencoded({ extended: true, limit: '50mb' }));
app.use(cookieParser());

// Serve uploaded media with proper cache controls
app.use('/uploads', express.static(path.resolve(process.cwd(), 'uploads')));

// Mount API routes
app.use('/api', apiRouter);

// Vite middleware in development or static dist in production
async function startServer() {
  const isProduction = process.env.NODE_ENV === 'production';

  if (isProduction && !process.env.FORCE_DEV) {
    const distPath = path.resolve(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  } else {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: {
        middlewareMode: true,
        hmr: process.env.DISABLE_HMR !== 'true',
        watch: process.env.DISABLE_HMR === 'true' ? null : {}
      },
      appType: 'spa'
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`ZORK CRAFT Server running on http://0.0.0.0:${PORT}`);
  });
}

startServer().catch(err => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
